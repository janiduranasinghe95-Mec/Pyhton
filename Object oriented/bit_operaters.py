a = 5
print(a << 1)  # Left shift operator, equivalent to multiplying by 2

b = 5
print(b >> 1)  # Right shift operator, equivalent to dividing by 2 (integer division)

c = 10
d = 2
print(c & d)   # Bitwise AND operator

print(c | d)   # Bitwise OR operato

print(~5)  # Bitwise NOT operator, flips the bits